// Command sandbox-crds writes canonical manifests and optional Helm chart copies.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/kubescape/storage/pkg/apis/sandbox/crd"
	"sigs.k8s.io/yaml"
)

func main() {
	output := flag.String("output", "artifacts/sandboxpolicy", "canonical manifest directory")
	chart := flag.String("chart-crds-dir", "", "optional Helm chart crds directory")
	flag.Parse()
	for _, definition := range crd.Definitions() {
		data, err := yaml.Marshal(definition)
		if err != nil {
			fail(err)
		}
		// CRD status is server-owned and must not appear in authored manifests.
		var manifest map[string]any
		if err = yaml.Unmarshal(data, &manifest); err != nil {
			fail(err)
		}
		delete(manifest, "status")
		if metadata, ok := manifest["metadata"].(map[string]any); ok {
			delete(metadata, "creationTimestamp")
		}
		data, err = yaml.Marshal(manifest)
		if err != nil {
			fail(err)
		}
		data = append([]byte("# Code generated by go run ./hack/sandbox-crds. DO NOT EDIT.\n"), data...)
		name := strings.ToLower(definition.Spec.Names.Kind) + ".crd.yaml"
		for _, dir := range []string{*output, *chart} {
			if dir == "" {
				continue
			}
			if err = os.MkdirAll(dir, 0755); err != nil {
				fail(err)
			}
			if err = os.WriteFile(filepath.Join(dir, name), data, 0644); err != nil {
				fail(err)
			}
			fmt.Println(filepath.Join(dir, name))
		}
	}
}
func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
